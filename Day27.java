public class Day27 {
    public static void main(String[] args) {
        int a = 10;
        int b = 10;

        System.out.println("=== INCREMENT (++) ===");
        System.out.println("Nilai a awal\t: " + a);
        a++; 
        System.out.println("Setelah a++\t: " + a);

        System.out.println("\n=== DECREMENT (--) ===");
        System.out.println("Nilai b awal\t: " + b);
        b--; 
        System.out.println("Setelah b--\t: " + b);
    }
}